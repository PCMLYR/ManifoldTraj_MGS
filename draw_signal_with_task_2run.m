function draw_signal_with_task_2run(signal_2run, task, max_frame_num, offset, figure_id)
    if ~exist('figure_id', 'var') figure_id = randi(100) + 1000; end
    
    draw_signal_with_task(signal_2run(1:max_frame_num,:), ...
        task, 'LR', 0, offset, figure_id);
    draw_signal_with_task(signal_2run((max_frame_num+1):2*max_frame_num,:), ...
        task, 'RL', max_frame_num, offset, figure_id);
    % plot(1:size(signal_2run,1), signal_2run, ...
    %     'Color',[0.8500 0.3250 0.0980], 'LineWidth', 2);
    plot(1:size(signal_2run,1), signal_2run, ...
        'Color','k', 'LineWidth', 1);
end